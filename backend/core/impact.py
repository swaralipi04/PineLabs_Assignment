"""Business Impact agent: translates a rate change into failed payments and rupees, and sizes recovery.

All numbers are computed (never generated by the LLM) and backed by queries shown as evidence.
Assumption (stated in the output): a failed payment is not recovered by a customer retry, so lost GMV
is an upper bound.
"""
from __future__ import annotations

from core import executor
from core.analysis import DriverReport, Evidence, merge_joins
from core.rbac import Role
from core.semantic import DIMENSIONS


def _ticket_sql(where: list[str], joins: list[str], start, end) -> str:
    w = " AND ".join([f"t.txn_date BETWEEN DATE '{start}' AND DATE '{end}'"] + where)
    return f"""SELECT AVG(CASE WHEN t.status = 'SUCCESS' THEN t.amount_inr END) AS avg_ticket_inr,
       SUM(CASE WHEN t.status = 'SUCCESS' THEN t.amount_inr ELSE 0 END) AS gmv_inr,
       SUM(CASE WHEN t.status IN ('SUCCESS','FAILED') THEN 1 ELSE 0 END) AS resolved_attempts
FROM transactions t {merge_joins(*joins)}
WHERE {w}"""


def inr_words(v: float) -> str:
    """Indian-style amount: ₹19.66 lakh / ₹1.23 crore (pre-formatted so the narrator never converts units)."""
    v = float(v or 0)
    if abs(v) >= 1e7:
        return f"₹{v / 1e7:.2f} crore"
    if abs(v) >= 1e5:
        return f"₹{v / 1e5:.2f} lakh"
    return f"₹{v:,.0f}"


def _seg_row(dim, segment):
    t = dim.table
    rows = t[t["segment"] == segment]
    return None if rows.empty else rows.iloc[0]


def compute(role: Role, rep: DriverReport, where: list[str], joins: list[str]) -> tuple[dict | None, list[Evidence]]:
    if rep.classification == "no_material_change" or not rep.primary:
        return None, []
    evidence: list[Evidence] = []
    focus = rep.focus

    sql = _ticket_sql(where, joins, focus.start, focus.end)
    r = executor.run(sql, role)
    evidence.append(Evidence(f"Business impact: average ticket and GMV, {focus.start}..{focus.end}", sql, r.df, r.elapsed_ms, r.cached))
    avg_ticket = float(r.df["avg_ticket_inr"].iloc[0] or 0)
    focus_gmv = float(r.df["gmv_inr"].iloc[0] or 0)

    days = focus.days
    drop = rep.base_rate - rep.focus_rate                    # positive = got worse
    direction = "lost" if drop > 0 else "gained"
    extra_failures = abs(drop) * rep.focus_n
    gmv_effect = extra_failures * avg_ticket
    out = {
        "direction": direction,
        "window": focus.to_dict(),
        "avg_ticket_inr": round(avg_ticket, 2),
        "extra_failed_payments": int(round(extra_failures)) if drop > 0 else 0,
        "extra_successful_payments": int(round(extra_failures)) if drop < 0 else 0,
        "gmv_impact_inr": round(gmv_effect, 0),
        "gmv_impact_display": inr_words(gmv_effect),
        "monthly_run_rate_display": inr_words(gmv_effect / days * 30),
        "gmv_impact_pct_of_window_gmv": round(gmv_effect / focus_gmv * 100, 2) if focus_gmv else None,
        "daily_run_rate_inr": round(gmv_effect / days, 0),
        "monthly_run_rate_inr": round(gmv_effect / days * 30, 0),
        "scenarios": [],
        "assumptions": [
            f"Failed payments are valued at the average successful ticket in the window (₹{avg_ticket:,.0f}).",
            "Assumes failed payments were not recovered by customer retries, so lost GMV is an upper bound.",
            "30-day run-rate assumes the issue persists at the same intensity.",
        ],
    }
    if drop <= 0:
        out["headline"] = f"Success rate improved: about {int(extra_failures):,} more successful payments (~₹{gmv_effect:,.0f}) than at the baseline rate."
        return out, evidence

    out["headline"] = (f"About {int(extra_failures):,} extra failed payments in {days} days, worth up to {inr_words(gmv_effect)} "
                       f"in GMV (~{inr_words(gmv_effect / days * 30)} per month if it persists).")

    if rep.classification == "mix_shift":
        mix_failures = max(0.0, -rep.primary.mix_total) * rep.focus_n
        out["scenarios"].append({
            "action": f"Return {rep.primary.label.lower()} mix to baseline shares",
            "segment": rep.primary.top_segment,
            "recovered_payments": int(round(mix_failures)),
            "recovered_gmv_inr": round(mix_failures * avg_ticket, 0),
            "note": "Traffic moved into a structurally lower-converting option; no segment's own performance got worse.",
        })
        return out, evidence

    # rate-driven: recovery if the most specific culprit segment returns to its baseline rate
    prim = rep.primary
    row = _seg_row(prim, prim.top_segment)
    if row is not None and row.base_rate == row.base_rate and row.focus_rate == row.focus_rate:
        rec = max(0.0, (row.base_rate - row.focus_rate) * row.focus_n)
        out["scenarios"].append({
            "action": f"Restore {prim.top_segment} ({prim.label.lower()}) to its baseline success rate",
            "segment": prim.top_segment,
            "recovered_payments": int(round(rec)),
            "recovered_gmv_inr": round(rec * avg_ticket, 0),
            "note": f"{row.base_rate * 100:.2f}% -> {row.focus_rate * 100:.2f}% on {int(row.focus_n):,} resolved attempts.",
        })
    if rep.drilldown:
        dd = rep.drilldown[0]
        drow = _seg_row(dd, dd.top_segment)
        if drow is not None and drow.base_rate == drow.base_rate and drow.focus_rate == drow.focus_rate:
            rec = max(0.0, (drow.base_rate - drow.focus_rate) * drow.focus_n)
            _, expr, pjoin = DIMENSIONS[prim.dimension]
            _, dexpr, djoin = DIMENSIONS[dd.dimension]
            seg_where = where + [f"{expr} = '{prim.top_segment.replace(chr(39), chr(39) * 2)}'",
                                 f"{dexpr} = '{dd.top_segment.replace(chr(39), chr(39) * 2)}'"]
            ssql = _ticket_sql(seg_where, joins + [pjoin, djoin], focus.start, focus.end)
            sr = executor.run(ssql, role)
            evidence.append(Evidence(f"Business impact: ticket size within {prim.top_segment} x {dd.top_segment}", ssql, sr.df, sr.elapsed_ms, sr.cached))
            seg_ticket = float(sr.df["avg_ticket_inr"].iloc[0] or avg_ticket)
            out["scenarios"].append({
                "action": f"Fix {dd.top_segment} within {prim.top_segment} (e.g. reroute or retry on an alternate path)",
                "segment": f"{prim.top_segment} x {dd.top_segment}",
                "recovered_payments": int(round(rec)),
                "recovered_gmv_inr": round(rec * seg_ticket, 0),
                "note": f"{drow.base_rate * 100:.2f}% -> {drow.focus_rate * 100:.2f}% on {int(drow.focus_n):,} resolved attempts; "
                        f"this segment explains {rec / extra_failures * 100:.0f}% of the extra failures.",
            })
    return out, evidence
